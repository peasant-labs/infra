package ratchet

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/peasant-labs/infra/stringly/internal/failure"
	"github.com/peasant-labs/infra/stringly/internal/rules"
)

// BaselineFormatVersion is the only baseline `version:` this tool reads and
// writes.
const BaselineFormatVersion = 1

// baselineComment is the fixed comment that opens every baseline file.
const baselineComment = "# Generated by `stringly update`. Do not edit and do not hand-merge.\n" +
	"# After a merge: take the incoming file, then run the repository's update command.\n"

// Versions are the tool and ast-grep versions a baseline header records, or
// that the running tool has.
type Versions struct {
	// Tool is the stringly version, for example "v0.1.0".
	Tool string
	// AstGrep is the ast-grep version, for example "0.51.2".
	AstGrep string
}

// Baseline is the committed record of allowed hits: a count per rule and
// file. The header names the tool and ast-grep versions that last verified
// the counts; it grants nothing.
type Baseline struct {
	// Header is the `tool` and `ast-grep` lines.
	Header Versions
	// Entries maps a rule to its files and their counts. Every count is above
	// zero; a rule with no entry is absent.
	Entries map[rules.RuleID]map[string]int
}

// Count returns the allowed count of rule id in file, and whether the
// baseline has an entry for it.
func (b Baseline) Count(id rules.RuleID, file string) (int, bool) {
	n, ok := b.Entries[id][file]
	return n, ok
}

type baselineDoc struct {
	Version int                       `yaml:"version"`
	Tool    string                    `yaml:"tool"`
	AstGrep string                    `yaml:"ast-grep"`
	Rules   map[string]map[string]int `yaml:"rules"`
}

// ParseBaseline reads baseline text. name is the file's path for messages.
// An unknown format version, an unknown key or rule id, or a count below one
// is a *failure.Error: the file cannot be compared.
func ParseBaseline(name string, data []byte) (Baseline, error) {
	where := "reading " + name + ", before the comparison. Nothing was written."
	regen := "take the file from the default branch and run the update command; never edit or hand-merge it."

	var probe struct {
		Version int `yaml:"version"`
	}
	if err := yaml.Unmarshal(data, &probe); err != nil {
		return Baseline{}, failure.New(
			fmt.Sprintf("the baseline %s is not valid YAML: %v.", name, err),
			"the baseline is generated by `stringly update`; a file that does not parse was edited or hand-merged.",
			where, regen)
	}
	if probe.Version != BaselineFormatVersion {
		return Baseline{}, failure.New(
			fmt.Sprintf("the baseline %s has format `version: %d`; this tool reads only `version: %d`.", name, probe.Version, BaselineFormatVersion),
			"a baseline of another format cannot be compared: its counts may mean something else.",
			where,
			"run the stringly version the repository pins (its Makefile or package.json names it); "+
				"a file of a newer format needs the stringly release that wrote it.")
	}

	var doc baselineDoc
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(&doc); err != nil && !errors.Is(err, io.EOF) {
		return Baseline{}, failure.New(
			fmt.Sprintf("the baseline %s does not decode: %v.", name, err),
			"the baseline holds exactly version, tool, ast-grep and rules; anything else means it was edited or hand-merged.",
			where, regen)
	}
	if doc.Tool == "" || doc.AstGrep == "" {
		return Baseline{}, failure.New(
			fmt.Sprintf("the baseline %s has no `tool` or no `ast-grep` header line.", name),
			"the header says which tool last verified the counts; every file the tool writes carries both lines.",
			where, regen)
	}
	b := Baseline{Header: Versions{Tool: doc.Tool, AstGrep: doc.AstGrep}, Entries: map[rules.RuleID]map[string]int{}}
	for ruleText, files := range doc.Rules {
		id, err := rules.ParseRuleID(ruleText)
		if err != nil {
			return Baseline{}, failure.New(
				fmt.Sprintf("the baseline %s has an entry for %q, which this tool does not know.", name, ruleText),
				err.Error()+".",
				where,
				"run the stringly version the repository pins; if the rule was removed, run its update command with that version.")
		}
		for file, n := range files {
			if n < 1 {
				return Baseline{}, failure.New(
					fmt.Sprintf("the baseline %s allows %d hits of %s in %s.", name, n, id, file),
					"a baseline count is always at least one; a rule or file with no hit has no entry.",
					where, regen)
			}
			if b.Entries[id] == nil {
				b.Entries[id] = map[string]int{}
			}
			b.Entries[id][file] = n
		}
	}
	return b, nil
}

// Format renders the baseline as the tool writes it: the fixed comment, the
// header, then rules sorted by id and files sorted by path, both in byte
// order. There are no totals and no timestamps, so formatting the same
// baseline twice gives the same bytes.
func (b Baseline) Format() []byte {
	var sb strings.Builder
	sb.WriteString(baselineComment)
	fmt.Fprintf(&sb, "version: %d\n", BaselineFormatVersion)
	fmt.Fprintf(&sb, "tool: %s\n", yamlScalar(b.Header.Tool))
	fmt.Fprintf(&sb, "ast-grep: %s\n", yamlScalar(b.Header.AstGrep))

	ids := make([]rules.RuleID, 0, len(b.Entries))
	for id, files := range b.Entries {
		if len(files) > 0 {
			ids = append(ids, id)
		}
	}
	if len(ids) == 0 {
		sb.WriteString("rules: {}\n")
		return []byte(sb.String())
	}
	slices.Sort(ids)
	sb.WriteString("rules:\n")
	for _, id := range ids {
		fmt.Fprintf(&sb, "  %s:\n", yamlScalar(id.String()))
		files := make([]string, 0, len(b.Entries[id]))
		for f := range b.Entries[id] {
			files = append(files, f)
		}
		slices.Sort(files)
		for _, f := range files {
			fmt.Fprintf(&sb, "    %s: %d\n", yamlScalar(f), b.Entries[id][f])
		}
	}
	return []byte(sb.String())
}

// yamlScalar renders a string as a YAML scalar, quoted only when YAML needs
// it to read the string back unchanged.
func yamlScalar(s string) string {
	out, err := yaml.Marshal(s)
	if err != nil {
		return fmt.Sprintf("%q", s)
	}
	text := strings.TrimSuffix(string(out), "\n")
	if strings.Contains(text, "\n") {
		return fmt.Sprintf("%q", s)
	}
	return text
}

// clone returns a deep copy of the entries.
func (b Baseline) clone() Baseline {
	c := Baseline{Header: b.Header, Entries: make(map[rules.RuleID]map[string]int, len(b.Entries))}
	for id, files := range b.Entries {
		m := make(map[string]int, len(files))
		for f, n := range files {
			m[f] = n
		}
		c.Entries[id] = m
	}
	return c
}
